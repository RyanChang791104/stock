prefix_codes = list(range(1101, 9960))
random.seed(2026)

for code in prefix_codes:
    if len(stocks) >= 8250:
        break
    symbol = f"{code}.TW"
    if any(s["symbol"].startswith(str(code)) for s in stocks):
        continue

    m_type = random.choice(["TWSE上市", "TPEx上櫃", "興櫃", "權證標的"])
    sec = random.choice(sectors)
    price = round(random.uniform(12.5, 680.0), 2)
